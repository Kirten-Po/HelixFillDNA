def test_prepare_source_file_is_noop_for_other_sources(tmp_path):
    path = tmp_path / "ftdna.csv"
    path.write_text("RSID,CHROMOSOME,POSITION,RESULT\nrs1,1,100,AA\n", encoding="utf-8")
    out, stats = pipeline.prepare_source_file("ftdna", path, tmp_path / "run")
    assert out == path
    assert stats is None
    assert not (tmp_path / "run").exists(), "для чужих источников папка даже не создаётся"


def test_prepare_source_file_converts_ancestry(tmp_path):
    src = _raw(tmp_path, "rs1\t1\t100\tA\tG\n")
    run_dir = tmp_path / "run"
    out, stats = pipeline.prepare_source_file(
        "ancestry", src, run_dir, template_path=_template(tmp_path),
    )
    assert out.parent == run_dir, "конвертированный файл кладётся в папку запуска"
    assert out.name.endswith("_23andme_v3.txt")
    assert stats is not None and not stats.skipped
    assert detect_layout(out) == "23andme"


def test_ancestry_listed_as_needing_conversion():
    assert "ancestry" in pipeline._SOURCES_NEEDING_CONVERSION
    assert "ftdna" not in pipeline._SOURCES_NEEDING_CONVERSION


def test_column_header_line_is_not_counted_as_malformed(tmp_path):
    """
    Регрессия: строку названий колонок сырого Ancestry не отличить от
    строки данных по количеству полей (в обеих пять, ведущего '#' нет).
    Конвертер обязан пропускать всё до заголовка включительно, иначе
    считает собственный заголовок испорченной строкой.
    """
    src = _raw(tmp_path, "rs1\t1\t100\tA\tG\nrs2\t1\t200\tC\tC\n")
    dst = tmp_path / "out.txt"
    stats = convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))
    assert stats.malformed_rows == 0
    assert stats.rows == 2
