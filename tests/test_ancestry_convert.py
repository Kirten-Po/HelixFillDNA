_MIXED_ROWS = (
    "rs_a1\t1\t100\tA\tG\n"
    "rs_a2\t1\t200\tC\tC\n"
    "rs_a3\t2\t300\tT\tT\n"
    "rs_miss\t2\t400\t0\t0\n"
    "rs_mt\t26\t500\tG\tG\n"
    "rs_par\t25\t600\tC\tC\n"
)


def _parse_both(tmp_path, rows):
    src = _raw(tmp_path, rows)
    dst = tmp_path / "converted.txt"
    convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))
    reference = _reference_from_raw(src)
    return src, dst, parse_ancestry_v2(src, reference), parse_ancestry_v2(dst, reference)


def test_layouts_are_recognised_by_adapter(tmp_path):
    src, dst, _, _ = _parse_both(tmp_path, _MIXED_ROWS)
    assert _find_header(src)[1] == LAYOUT_RAW
    assert _find_header(dst)[1] == LAYOUT_CONVERTED


def test_raw_and_converted_give_identical_result(tmp_path):
    """
    Главная гарантия Этапа 0: конвертация ничего не теряет и ничего не
    меняет. Если сигнатуры разойдутся — разойдётся и кэш доноров.
    """
    _src, _dst, from_raw, from_converted = _parse_both(tmp_path, _MIXED_ROWS)

    assert from_raw.chip_signature == from_converted.chip_signature
    assert from_raw.chip_signature_broad == from_converted.chip_signature_broad
    assert from_raw.total_measured == from_converted.total_measured
    assert from_raw.missing == from_converted.missing

    # Сравнение по содержимому, а не по порядку: у сырого файла PAR (код
    # 25) идёт ПОСЛЕ Y и MT, а конвертер пересортировывает строки, слив
    # PAR с X. Порядок вариантов ни на что не влияет — build_vcf() всё
    # равно сортирует их сам (core/pure_python_core.py::build_vcf,
    # key=(_chrom_sort_key(chrom), pos)); важно, что набор совпадает.
    def _content(result):
        return sorted(
            (v.rsid, v.chrom, v.pos, v.ref, v.alt, v.gt) for v in result.variants
        )

    assert _content(from_raw) == _content(from_converted)


def test_haploid_single_letter_not_lost(tmp_path):
    """
    Регрессия: односимвольный генотип MT ('G' вместо 'GG') не должен
    уходить в invalid_codes. Именно на этом гибкий parse_myheritage_v5()
    молча потерял бы 259 позиций MT/Y реального файла.
    """
    _src, _dst, from_raw, from_converted = _parse_both(tmp_path, _MIXED_ROWS)
    assert from_converted.invalid_codes == 0
    assert "MT" in {v.chrom for v in from_converted.variants}
    assert {v.chrom for v in from_raw.variants} == {v.chrom for v in from_converted.variants}


def test_male_haploid_x_round_trip(tmp_path):
    """То же самое для X мужского образца — там одной буквой пишется вся X."""
    rows = "".join(f"rs_x{i}\t23\t{100 + i}\tA\tA\n" for i in range(10))
    _src, _dst, from_raw, from_converted = _parse_both(tmp_path, rows)
    assert from_converted.invalid_codes == 0
    assert from_raw.chip_signature == from_converted.chip_signature


