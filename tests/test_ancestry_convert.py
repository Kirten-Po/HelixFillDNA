def test_output_has_v3_layout(tmp_path):
    src = _raw(tmp_path, "rs1\t1\t100\tA\tG\nrs2\t1\t200\tC\tC\n")
    dst = tmp_path / "out.txt"
    convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))

    blob = dst.read_bytes()
    assert b"\r\n" not in blob, "v3 — это LF, а не CRLF"
    assert blob.startswith(b"# This data file generated by 23andMe at:")
    assert b"# rsid\tchromosome\tposition\tgenotype\n" in blob

    rows = _data_lines(dst)
    assert all(len(r) == 4 for r in rows), "в v3 ровно четыре колонки"
    assert rows[0] == ["rs1", "1", "100", "AG"]


def test_zero_allele_becomes_double_dash(tmp_path):
    src = _raw(tmp_path, "rs1\t1\t100\t0\t0\n")
    dst = tmp_path / "out.txt"
    stats = convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))
    assert _data_lines(dst)[0][3] == "--"
    assert stats.no_call == 1


def test_chrom_codes_become_letters(tmp_path):
    src = _raw(tmp_path, "rs_x\t23\t100\tA\tG\nrs_y\t24\t100\tT\tT\nrs_mt\t26\t100\tC\tC\n")
    dst = tmp_path / "out.txt"
    convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))
    assert [r[1] for r in _data_lines(dst)] == ["X", "Y", "MT"]


def test_par_merged_into_x_and_resorted(tmp_path):
    """
    У Ancestry PAR (код 25) идёт ПОСЛЕ Y. После слияния с X он обязан
    встать на своё место внутри X, иначе файл перестаёт быть
    отсортированным по (хромосома, позиция).
    """
    src = _raw(tmp_path, (
        "rs_x2\t23\t900\tA\tG\n"
        "rs_y\t24\t100\tT\tT\n"
        "rs_par\t25\t50\tC\tC\n"
    ))
    dst = tmp_path / "out.txt"
    stats = convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))

    assert stats.par_merged_into_x == 1
    rows = _data_lines(dst)
    assert [(r[1], int(r[2])) for r in rows] == [("X", 50), ("X", 900), ("Y", 100)]


