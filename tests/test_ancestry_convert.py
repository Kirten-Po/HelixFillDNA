def test_mt_written_as_single_letter(tmp_path):
    src = _raw(tmp_path, "rs_mt\t26\t100\tC\tC\nrs_auto\t1\t100\tC\tC\n")
    dst = tmp_path / "out.txt"
    stats = convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))
    by_rsid = {r[0]: r[3] for r in _data_lines(dst)}
    assert by_rsid["rs_mt"] == "C", "MT в 23andMe пишется одной буквой"
    assert by_rsid["rs_auto"] == "CC", "аутосома остаётся двумя"
    assert stats.haploid_single_letter == 1


def test_female_x_stays_diploid(tmp_path):
    rows = "".join(f"rs_x{i}\t23\t{100 + i}\tA\tG\n" for i in range(10))
    src = _raw(tmp_path, rows)
    dst = tmp_path / "out.txt"
    stats = convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))
    assert not stats.male
    assert all(len(r[3]) == 2 for r in _data_lines(dst))


def test_male_x_collapsed_to_single_letter(tmp_path):
    rows = "".join(f"rs_x{i}\t23\t{100 + i}\tA\tA\n" for i in range(10))
    src = _raw(tmp_path, rows)
    dst = tmp_path / "out.txt"
    stats = convert_ancestry_to_23andme_v3(src, dst, template_path=_template(tmp_path))
    assert stats.male
    assert all(r[3] == "A" for r in _data_lines(dst))


