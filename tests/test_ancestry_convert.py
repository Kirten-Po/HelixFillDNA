RAW_HEADER = "\n".join(
    ["#AncestryDNA raw data download"]
    + [f"#comment {i}" for i in range(17)]
    + ["rsid\tchromosome\tposition\tallele1\tallele2"]
)

TEMPLATE_HEADER = (
    "# This data file generated by 23andMe at: \n"
    "#\n"
    "# rsid\tchromosome\tposition\tgenotype\n"
)


def _raw(tmp_path: Path, rows: str, name: str = "AncestryDNA.txt") -> Path:
    path = tmp_path / name
    # CRLF — как в настоящих файлах Ancestry.
    #
    # newline="" здесь обязателен: без него текстовый режим на Windows
    # переводит каждый '\n' в '\r\n', и записанные нами '\r\n'
    # превращаются в '\r\r\n'. Файл после этого читается как удвоенное
    # число строк (пустая строка после каждой настоящей), и индекс
    # строки заголовка уезжает: 18 -> 36. На Linux этого не видно —
    # перевода нет, поэтому тест зелёный там и красный на Windows.
    path.write_text((RAW_HEADER + "\n" + rows).replace("\n", "\r\n"),
                    encoding="utf-8", newline="")
    return path


def _template(tmp_path: Path) -> Path:
    path = tmp_path / "template_v3.txt"
    path.write_text(TEMPLATE_HEADER + "rs1\t1\t100\tAA\n", encoding="utf-8")
    return path


def _data_lines(path: Path) -> list[list[str]]:
    return [
        line.split("\t")
        for line in path.read_text(encoding="utf-8").splitlines()
        if line and not line.startswith("#")
    ]


class _StubReference:
    """Отдаёт первый аллель самой строки как референсное основание —
    так разрешение ориентации не отбраковывает тестовые данные."""

    def __init__(self, bases: dict[tuple[str, int], str]):
        self._bases = bases

    def base_at(self, chrom: str, pos: int) -> str:
        return self._bases.get((chrom, pos), "A")


def _reference_from_raw(path: Path) -> _StubReference:
    from adapters.ancestry_v2 import _normalize_chrom
    bases = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or line.startswith("rsid\t"):
            continue
        parts = line.split("\t")
        if len(parts) == 5 and parts[3] in "ACGT":
            bases[(_normalize_chrom(parts[1]), int(parts[2]))] = parts[3]
    return _StubReference(bases)


